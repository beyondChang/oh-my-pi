/**
 * GitHub Releases as omp's only update version source.
 *
 * A release counts only once its `SHA256SUMS.txt` asset is uploaded, so a
 * check never offers a version whose binary cannot be verified. Metadata comes
 * from the GitHub REST API; the checksum manifest and the host's binary are
 * downloaded from the Release's public `github.com` URLs. Public repositories
 * need no token; `GITHUB_TOKEN`/`GH_TOKEN` is sent when present.
 */
import { $env, compareVersions, isRecord, USER_AGENT, VERSION } from "@oh-my-pi/pi-utils";
import {
	isTimeoutError,
	isUnsupportedProxyError,
	unsupportedProxyMessage,
	withTimeoutSignal,
} from "../utils/fetch-timeout";
import {
	type BuildAnswer,
	type BuildHost,
	currentBuildHost,
	type Fetch,
	OMP_BUILD,
	type UpdateChannel,
} from "./build-service";

/** Default repository; `OMP_UPDATE_REPO=owner/name` overrides it. */
export const DEFAULT_UPDATE_REPO = "beyondChang/oh-my-pi";

/** Checksum manifest generated by `ci:release:checksums` and shipped with every release. */
export const CHECKSUMS_ASSET = "SHA256SUMS.txt";

/** Upper bound of releases searched for one channel (GitHub pages them by published date). */
const MAX_RELEASES = 100;
const RELEASES_PER_PAGE = 30;
const RELEASE_METADATA_TIMEOUT_MS = 30_000;
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/;
const SHA256_HEX = /^[a-f0-9]{64}$/;
const REPO_SLUG = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;
const CHECKSUM_LINE = /^([a-fA-F0-9]{64})\s+\*?(.+)$/;

/** One asset of a release, as the GitHub API reports it. */
export interface ReleaseAsset {
	name: string;
	size: number;
	downloadUrl: string;
}

/** A resolved, published release on a channel. */
export interface GitHubRelease {
	version: string;
	tag: string;
	repo: string;
	channel: UpdateChannel;
	assets: readonly ReleaseAsset[];
}

/** Options for {@link getLatestRelease}. */
export interface LatestReleaseOptions {
	timeoutMs?: number;
	channel?: UpdateChannel;
	/** `owner/name`; defaults to {@link updateRepo}. */
	repo?: string;
	fetchImpl?: Fetch;
}

/** Options for {@link fetchReleaseBuild}. */
export interface ReleaseBuildOptions {
	timeoutMs?: number;
	fetchImpl?: Fetch;
	host?: BuildHost;
}

/** Repository slug from `OMP_UPDATE_REPO`, accepting a full GitHub URL; throws when it is not `owner/name`. */
export function updateRepo(repo: string | undefined = $env.OMP_UPDATE_REPO): string {
	const trimmed = (repo ?? "").trim();
	if (trimmed === "") return DEFAULT_UPDATE_REPO;
	const slug = trimmed
		.replace(/^https?:\/\/github\.com\//i, "")
		.replace(/\.git$/, "")
		.replace(/\/$/, "");
	if (!REPO_SLUG.test(slug)) {
		throw new Error(`Invalid OMP_UPDATE_REPO "${trimmed}": expected owner/name`);
	}
	return slug;
}

function apiHeaders(): Record<string, string> {
	const headers: Record<string, string> = {
		Accept: "application/vnd.github+json",
		"X-GitHub-Api-Version": "2022-11-28",
		"User-Agent": USER_AGENT,
	};
	const token = $env.GITHUB_TOKEN ?? $env.GH_TOKEN;
	if (token) headers.Authorization = `Bearer ${token}`;
	return headers;
}

async function githubJson(fetchImpl: Fetch, url: string, timeoutMs: number): Promise<unknown> {
	let response: Response;
	try {
		response = await fetchImpl(url, { headers: apiHeaders(), signal: withTimeoutSignal(timeoutMs) });
	} catch (err) {
		if (isTimeoutError(err)) {
			throw new Error(`Timed out asking GitHub for ${url} after ${Math.round(timeoutMs / 1000)}s`, { cause: err });
		}
		if (isUnsupportedProxyError(err)) throw new Error(unsupportedProxyMessage(), { cause: err });
		throw err;
	}
	if (!response.ok) {
		throw new Error(`GitHub answered ${response.status} ${response.statusText} for ${url}`);
	}
	try {
		return await response.json();
	} catch (err) {
		if (!(err instanceof SyntaxError)) throw err;
		throw new Error(`Malformed GitHub response for ${url}`);
	}
}

function toAsset(value: unknown): ReleaseAsset | undefined {
	if (
		!isRecord(value) ||
		typeof value.name !== "string" ||
		typeof value.size !== "number" ||
		!Number.isSafeInteger(value.size) ||
		value.size <= 0 ||
		typeof value.browser_download_url !== "string"
	) {
		return undefined;
	}
	return { name: value.name, size: value.size, downloadUrl: value.browser_download_url };
}

/** Version a release tag names, or undefined for tags that are not omp versions. */
function versionFromTag(tag: string): string | undefined {
	const version = tag.startsWith("v") ? tag.slice(1) : tag;
	return SEMVER.test(version) ? version : undefined;
}

function channelOf(version: string, prerelease: boolean): UpdateChannel {
	return prerelease || version.includes("-canary.") ? "canary" : "stable";
}

/** A release from the API, or undefined when it lacks the fields a check needs. */
function parseRelease(value: unknown, repo: string): GitHubRelease | undefined {
	if (!isRecord(value) || typeof value.tag_name !== "string") return undefined;
	if (value.draft === true || typeof value.prerelease !== "boolean") return undefined;
	const version = versionFromTag(value.tag_name);
	if (!version || !Array.isArray(value.assets)) return undefined;
	const assets = value.assets.map(toAsset).filter((asset): asset is ReleaseAsset => asset !== undefined);
	if (!assets.some(asset => asset.name === CHECKSUMS_ASSET)) return undefined;
	return { version, tag: value.tag_name, repo, channel: channelOf(version, value.prerelease), assets };
}

/**
 * Newest published release on `channel`, by GitHub's published-date order.
 *
 * Releases without a version tag, drafts, and releases whose `SHA256SUMS.txt`
 * has not been uploaded yet are skipped, so the answer is always installable
 * and verifiable. Throws when no release on the channel qualifies.
 */
export async function getLatestRelease(options: LatestReleaseOptions = {}): Promise<GitHubRelease> {
	const timeoutMs = options.timeoutMs ?? RELEASE_METADATA_TIMEOUT_MS;
	const channel = options.channel ?? "stable";
	const repo = updateRepo(options.repo);
	const fetchImpl = options.fetchImpl ?? fetch;
	for (let page = 1; (page - 1) * RELEASES_PER_PAGE < MAX_RELEASES; page++) {
		const url = `https://api.github.com/repos/${repo}/releases?per_page=${RELEASES_PER_PAGE}&page=${page}`;
		const body = await githubJson(fetchImpl, url, timeoutMs);
		if (!Array.isArray(body)) throw new Error(`Malformed GitHub response for ${url}`);
		for (const item of body) {
			const release = parseRelease(item, repo);
			if (release?.channel === channel) return release;
		}
		if (body.length < RELEASES_PER_PAGE) break;
	}
	const hint = channel === "canary" ? " Try `omp update --stable`." : "";
	throw new Error(`No published ${channel} release with ${CHECKSUMS_ASSET} in ${repo}.${hint}`);
}

function checksumFor(name: string, manifest: string): string {
	for (const line of manifest.split(/\r?\n/)) {
		const match = CHECKSUM_LINE.exec(line.trim());
		if (match?.[2] === name) return match[1].toLowerCase();
	}
	throw new Error(`${CHECKSUMS_ASSET} has no checksum for ${name}`);
}

async function downloadText(fetchImpl: Fetch, url: string, timeoutMs: number): Promise<string> {
	let response: Response;
	try {
		response = await fetchImpl(url, { redirect: "follow", signal: withTimeoutSignal(timeoutMs) });
	} catch (err) {
		if (isTimeoutError(err)) {
			throw new Error(`Timed out downloading ${url} after ${Math.round(timeoutMs / 1000)}s`, { cause: err });
		}
		if (isUnsupportedProxyError(err)) throw new Error(unsupportedProxyMessage(), { cause: err });
		throw err;
	}
	if (!response.ok) throw new Error(`Download failed: ${response.status} ${response.statusText} for ${url}`);
	return await response.text();
}

function requireAsset(release: GitHubRelease, name: string): ReleaseAsset {
	const asset = release.assets.find(candidate => candidate.name === name);
	if (!asset) throw new Error(`Release ${release.tag} of ${release.repo} has no ${name} asset`);
	return asset;
}

/**
 * Resolve this host's binary for `release`, verified against
 * `SHA256SUMS.txt`. The answer installs exactly like a build-service answer:
 * whole file, no patch, the same size/SHA-256 checks while streaming.
 */
export async function fetchReleaseBuild(
	release: GitHubRelease,
	options: ReleaseBuildOptions = {},
): Promise<BuildAnswer> {
	const timeoutMs = options.timeoutMs ?? RELEASE_METADATA_TIMEOUT_MS;
	const fetchImpl = options.fetchImpl ?? fetch;
	const host = options.host ?? (await currentBuildHost());
	const fileName = OMP_BUILD.fileName(host, release.version);
	const manifest = await downloadText(fetchImpl, requireAsset(release, CHECKSUMS_ASSET).downloadUrl, timeoutMs);
	const sha256 = checksumFor(fileName, manifest);
	if (!SHA256_HEX.test(sha256)) throw new Error(`${CHECKSUMS_ASSET} has a malformed checksum for ${fileName}`);
	const asset = requireAsset(release, fileName);
	if (new URL(asset.downloadUrl).protocol !== "https:") throw new Error(`${fileName} has no HTTPS download`);
	return {
		version: release.version,
		file: { name: fileName, size: asset.size, sha256 },
		download: asset.downloadUrl,
	};
}

/** Whether `candidate` is newer than the running build. */
export function isNewerVersion(candidate: string, currentVersion = VERSION): boolean {
	return compareVersions(candidate, currentVersion) > 0;
}
